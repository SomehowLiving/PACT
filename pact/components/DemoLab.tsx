"use client";

import { VerdictPill } from "@/components/VerdictPill";
import type { DeskPayload } from "@/components/useDesk";
import { reasonLabel, shortAddr, usd } from "@/lib/format";
import type { CopyAction, DemoCase, Proposal } from "@/lib/types";

type CaseMeta = {
  profile: string;
  label: string;
  intent: string;
  rule: string;
};

const CASES: Record<DemoCase, CaseMeta> = {
  CORE_TWAP_COPY: {
    profile: "CORE",
    label: "Liquid ETH accumulation",
    intent: "TWAP inside the published entry window",
    rule: "Within pair, order, sleeve, and portfolio limits",
  },
  SLEEVE_SCALE: {
    profile: "CORE",
    label: "Per-leader sleeve clipping",
    intent: "Limit entry that exceeds this leader's daily sleeve",
    rule: "Leader daily allocation cap",
  },
  MARKET_REFUSAL: {
    profile: "FAST",
    label: "Market chase refusal",
    intent: "Immediate market buy after price movement",
    rule: "Market execution not enabled by the mandate",
  },
  EXPIRED_PLAN: {
    profile: "CORE",
    label: "Expired entry window",
    intent: "Limit entry after the plan's expiry",
    rule: "Entry window already closed",
  },
  LOW_RR_CAUTION: {
    profile: "CORE",
    label: "Low reward:risk caution",
    intent: "TWAP with a declared 1:1 reward:risk",
    rule: "Recorded as caution; strict plan-quality gate is optional",
  },
  EVIDENCE_REVIEW: {
    profile: "STRICT",
    label: "Execution evidence review",
    intent: "Limit entry from an unverified leader plan",
    rule: "Follower requires verified leader execution evidence",
  },
  HIGH_BETA_PAIR_REFUSAL: {
    profile: "HIGH-BETA",
    label: "Unsupported asset refusal",
    intent: "Limit entry for an asset outside the allowlist",
    rule: "Only explicitly approved pairs can reach execution",
  },
};

const CASE_ORDER: DemoCase[] = [
  "CORE_TWAP_COPY",
  "SLEEVE_SCALE",
  "MARKET_REFUSAL",
  "EXPIRED_PLAN",
  "LOW_RR_CAUTION",
  "EVIDENCE_REVIEW",
  "HIGH_BETA_PAIR_REFUSAL",
];

function actionLabel(action: CopyAction) {
  return action.toLowerCase().replaceAll("_", " ");
}

function proposalForCase(state: DeskPayload | null, demoCase: DemoCase): Proposal | undefined {
  return state?.proposals.find((proposal) => proposal.demoCase === demoCase);
}

export function DemoLab({ state }: { state: DeskPayload | null }) {
  const cases = CASE_ORDER.map((demoCase) => ({
    demoCase,
    meta: CASES[demoCase],
    proposal: proposalForCase(state, demoCase),
  }));
  const completed = cases.filter(({ proposal }) => proposal).length;

  return (
    <section className="terminal-panel overflow-hidden lg:col-span-2">
      <div className="flex flex-col gap-3 border-b border-line px-5 py-4 md:flex-row md:items-end md:justify-between">
        <div>
          <div className="terminal-kicker">policy simulation matrix</div>
          <h2 className="mt-1 text-lg font-semibold tracking-tight text-ink">
            Seven deterministic copy-trade decisions
          </h2>
          <p className="mt-1 max-w-2xl text-xs leading-relaxed text-mute">
            Each row is generated by the same proposal and policy engine used before signing.
            It is not a price prediction, backtest, or claim of live high-beta execution.
          </p>
        </div>
        <div className="font-mono text-xs text-mute">
          cases loaded <span className="text-ink">{completed}/7</span>
        </div>
      </div>

      <div className="overflow-x-auto">
        <table className="w-full min-w-[940px] border-collapse text-left text-xs">
          <thead className="border-b border-line bg-[#0c1219] text-[10px] uppercase tracking-[0.13em] text-mute">
            <tr>
              <th className="px-5 py-3 font-medium">Scenario</th>
              <th className="px-4 py-3 font-medium">Leader intent</th>
              <th className="px-4 py-3 font-medium">Policy trigger</th>
              <th className="px-4 py-3 font-medium">Requested</th>
              <th className="px-4 py-3 font-medium">Outcome</th>
              <th className="px-5 py-3 font-medium">Approved / reason</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-line">
            {cases.map(({ demoCase, meta, proposal }) => {
              const decision = proposal ? state?.decisions[proposal.id] : undefined;
              const approved = decision?.modifiedQty ? Number(decision.modifiedQty) : proposal?.notionalUsd;
              return (
                <tr key={demoCase} className="align-top transition-colors hover:bg-white/[0.02]">
                  <td className="px-5 py-4">
                    <div className="flex items-center gap-2">
                      <span className="terminal-tag">{meta.profile}</span>
                      <span className="font-medium text-ink">{meta.label}</span>
                    </div>
                    {proposal ? (
                      <div className="mt-1 font-mono text-[10px] text-mute">
                        {proposal.orderType.toUpperCase()} · {shortAddr(proposal.follower)}
                      </div>
                    ) : null}
                  </td>
                  <td className="px-4 py-4 leading-relaxed text-mute">{meta.intent}</td>
                  <td className="px-4 py-4 leading-relaxed text-mute">{meta.rule}</td>
                  <td className="px-4 py-4 font-mono text-ink">
                    {proposal ? usd(proposal.notionalUsd) : "Load demo"}
                  </td>
                  <td className="px-4 py-4">
                    {decision ? (
                      <div className="flex items-center gap-2">
                        <VerdictPill verdict={decision.verdict} />
                        <span className="font-mono text-[10px] uppercase text-mute">
                          {actionLabel(decision.action)}
                        </span>
                      </div>
                    ) : (
                      <span className="text-mute">Not loaded</span>
                    )}
                  </td>
                  <td className="px-5 py-4">
                    {decision && proposal ? (
                      <>
                        <div className="font-mono text-ink">
                          {decision.verdict === "BLOCK" ? "$0.00" : usd(approved ?? 0)}
                        </div>
                        <div className="mt-1 max-w-[220px] leading-relaxed text-mute">
                          {decision.reasons.length
                            ? decision.reasons.map(reasonLabel).join(" · ")
                            : proposal.leaderPlanGrade === "CAUTION"
                              ? "Plan quality: caution (copy remains enabled)"
                              : "Policy satisfied"}
                        </div>
                      </>
                    ) : (
                      <span className="text-mute">—</span>
                    )}
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
      <div className="border-t border-line px-5 py-3 text-[11px] leading-relaxed text-mute">
        Current executable pair coverage is WETH/USDC on Base and Arc. The high-beta row proves
        the refusal path; it does not represent a supported memecoin market.
      </div>
    </section>
  );
}
